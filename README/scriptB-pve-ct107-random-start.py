#!/usr/bin/env python3
# Script B -- random startup of PVE CT 107
#   Name  : /usr/local/sbin/pve-ct107-random-start.py
#   Cron  : /etc/cron.d/pve-ct107-random-start
#   State : /var/lib/ct107-random-start/plan.json
#   Log   : /var/log/ct107-random-start.log
#   Rule  : start CT 107 once per day at a Gaussian-random moment between
#           08:00 and 08:30 CST. 08:10 is the MODE (most frequent value),
#           NOT the mean: mu is set directly to 10.0 min and sigma=6min is
#           the jitter. Since mu lies inside [0,30], truncation cannot move
#           the mode; it only pushes the mean slightly higher (~08:10.6).
#   Note  : runs on the PVE host (always on). Script A stops CT 107 at 00:00
#           and deliberately does NOT start it at 09:00.
#   Change: 2026-11-12 23:20 -- mean-calibration removed per user's
#           clarification that "08:10" means the mode, not the average.
#
import argparse
import fcntl
import json
import math
import os
import random
import subprocess
import sys
import time
from datetime import datetime, timedelta, timezone
from pathlib import Path

BJ = timezone(timedelta(hours=8))
CTID = "107"
MODE_MIN = 10.0             # 08:10 -- the MOST FREQUENT offset (min after 08:00)
SIGMA = 6.0                 # jitter / spread; raise for wider scatter
LO, HI = 0.0, 30.0          # hard window 08:00-08:30
MAX_ATTEMPTS = 3
DEFAULT_STATE = Path("/var/lib/ct107-random-start/plan.json")
LOG_FILE = Path("/var/log/ct107-random-start.log")
LOCK_FILE = Path("/run/ct107-random-start.lock")


def bj_now():
    return datetime.now(BJ)


def window_start(day):
    return datetime(day.year, day.month, day.day, 8, 0, 0, tzinfo=BJ)


def norm_pdf(x):
    return math.exp(-x * x / 2.0) / math.sqrt(2.0 * math.pi)


def norm_cdf(x):
    return 0.5 * (1.0 + math.erf(x / math.sqrt(2.0)))


def truncated_expectation(mu, sigma, lo, hi):
    """Informational only: the mean is explicitly NOT the centre we target."""
    a, b = (lo - mu) / sigma, (hi - mu) / sigma
    z = norm_cdf(b) - norm_cdf(a)
    if z <= 1e-12:
        return mu
    return mu + sigma * (norm_pdf(a) - norm_pdf(b)) / z


# For a truncated normal with lo <= mu <= hi, the density keeps its peak at
# mu, so the MODE is exactly mu. No mean-calibration is wanted here.
MU = MODE_MIN


def truncated_normal(mu, sigma, lo, hi):
    for _ in range(1000):
        x = random.gauss(mu, sigma)
        if lo <= x <= hi:
            return x
    return min(max(mu, lo), hi)


def log(msg):
    line = "%s [scriptB] %s" % (bj_now().strftime("%Y-%m-%d %H:%M:%S %z"), msg)
    with LOG_FILE.open("a", encoding="utf-8") as f:
        f.write(line + "\n")


def load_state(path):
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None


def save_state(path, state):
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(json.dumps(state, ensure_ascii=False, indent=2), encoding="utf-8")
    os.replace(tmp, path)


def build_plan(now=None):
    now = now or bj_now()
    base = window_start(now.date())
    offset = truncated_normal(MU, SIGMA, LO, HI)
    planned = base + timedelta(minutes=offset)
    return {
        "date": now.date().isoformat(),
        "offset_min": round(offset, 4),
        "planned_epoch": planned.timestamp(),
        "planned_bj": planned.isoformat(),
        "launched": False,
        "launched_at_bj": None,
        "attempts": 0,
        "pct_exit_code": None,
        "note": "generated by Script B (mode=08:10, sigma=6min)",
    }


def pct_status():
    try:
        r = subprocess.run(["pct", "status", CTID], capture_output=True, text=True, timeout=30)
    except Exception:
        return "unknown"
    for line in (r.stdout or "").splitlines():
        if line.startswith("status:"):
            return line.split(":", 1)[1].strip()
    return "unknown"


def cmd_plan(args):
    state = build_plan()
    if not args.dry_run:
        save_state(args.state, state)
        log("plan: date=%s planned=%s offset=%.2fmin" % (state["date"], state["planned_bj"], state["offset_min"]))
    print(json.dumps(state, ensure_ascii=False, indent=2))
    return 0


def cmd_launch(args):
    if args.dry_run:
        state = load_state(args.state) or build_plan()
        print("DRY-RUN: planned=%s now=%s ct_status=%s" % (state["planned_bj"], bj_now().isoformat(), pct_status()))
        return 0
    now = bj_now()
    state = load_state(args.state)
    if not state or state.get("date") != now.date().isoformat():
        state = build_plan(now)
        save_state(args.state, state)
        log("plan (on-demand): planned=%s" % state["planned_bj"])
    if state.get("launched"):
        return 0
    if not args.force and time.time() < float(state["planned_epoch"]):
        return 0
    if int(state.get("attempts", 0)) >= MAX_ATTEMPTS:
        return 0
    if not args.force and now > window_start(now.date()) + timedelta(minutes=HI + 1):
        log("window closed, CT %s not started (attempts=%d)" % (CTID, state["attempts"]))
        state["launched"] = True
        save_state(args.state, state)
        return 1
    st = pct_status()
    if st == "running":
        state["launched"] = True
        state["launched_at_bj"] = now.isoformat()
        state["pct_exit_code"] = 0
        state["note"] = "already running, skip pct start"
        save_state(args.state, state)
        log("CT %s already running, skip" % CTID)
        return 0
    try:
        r = subprocess.run(["pct", "start", CTID], capture_output=True, text=True, timeout=180)
        rc = r.returncode
        detail = ((r.stdout or "") + (r.stderr or "")).strip().replace("\n", " ")[:300]
    except Exception as e:
        rc, detail = -1, "%s: %s" % (type(e).__name__, e)
    state["attempts"] = int(state.get("attempts", 0)) + 1
    state["pct_exit_code"] = rc
    if rc == 0:
        state["launched"] = True
        state["launched_at_bj"] = now.isoformat()
        state["note"] = "pct start OK"
        log("CT %s started (planned %s, attempt %d)" % (CTID, state["planned_bj"], state["attempts"]))
    else:
        state["note"] = "pct start FAILED: " + detail
        log("CT %s start FAILED (rc=%d, attempt %d): %s" % (CTID, rc, state["attempts"], detail))
    save_state(args.state, state)
    return 0 if rc == 0 else 1


def cmd_status(args):
    state = load_state(args.state)
    if not state:
        print("no plan yet (waiting for 07:59)")
    else:
        print(json.dumps(state, ensure_ascii=False, indent=2))
    print("distribution: mode=08:%02d (mu=%.1fmin), sigma=%.1fmin, window=[%.0f,%.0f]min, mean=%.2fmin (informational)"
          % (int(MODE_MIN), MU, SIGMA, LO, HI, truncated_expectation(MU, SIGMA, LO, HI)))
    print("CT %s status: %s" % (CTID, pct_status()))
    print("now: %s" % bj_now().isoformat())
    return 0


def cmd_selftest(args):
    n = 5000
    vals = sorted(truncated_normal(MU, SIGMA, LO, HI) for _ in range(n))
    p5, p50, p95 = vals[int(0.05 * n)], vals[int(0.50 * n)], vals[int(0.95 * n)]
    bins = {}
    for v in vals:
        b = int(v // 1.0)
        bins[b] = bins.get(b, 0) + 1
    peak = max(bins, key=bins.get)
    mean = sum(vals) / n
    in_window = all(LO <= v <= HI for v in vals)
    print("samples=%d mode=08:%02d (%.1fmin) sigma=%.1fmin window=[%.0f,%.0f]min"
          % (n, int(MODE_MIN), MODE_MIN, SIGMA, LO, HI))
    print("nominal_mu=%.3f  mean_after_truncation=%.3f (informational, NOT the centre)"
          % (MU, truncated_expectation(MU, SIGMA, LO, HI)))
    print("min=%.2f P5=%.2f P50=%.2f P95=%.2f max=%.2f sampled_mean=%.3f"
          % (vals[0], p5, p50, p95, vals[-1], mean))
    print("modal_1min_bin=[%d,%d) count=%d all_in_window=%s"
          % (peak, peak + 1, bins[peak], in_window))
    ok = in_window and abs((peak + 0.5) - MODE_MIN) <= 1.5
    print("SELFTEST %s" % ("OK" if ok else "FAILED"))
    return 0 if ok else 1


def main():
    p = argparse.ArgumentParser(description="Script B: random start of CT 107")
    p.add_argument("command", choices=["plan", "launch", "status", "selftest"])
    p.add_argument("--state", type=Path, default=DEFAULT_STATE)
    p.add_argument("--dry-run", action="store_true")
    p.add_argument("--force", action="store_true")
    args = p.parse_args()
    if args.command in ("plan", "launch"):
        try:
            lock = LOCK_FILE.open("a+")
            fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except OSError:
            print("another instance is running, skip", file=sys.stderr)
            return 0
    cmds = {"plan": cmd_plan, "launch": cmd_launch, "status": cmd_status, "selftest": cmd_selftest}
    return cmds[args.command](args)


if __name__ == "__main__":
    sys.exit(main())
